create table vendors (
    id bigint generated by default as identity primary key,
    vendor_type varchar(20) not null,
    name varchar(150) not null,
    name_key varchar(150) not null unique,
    cr_number varchar(100),
    vat_number varchar(15),
    national_address varchar(500),
    classification varchar(60),
    commission numeric(5,2) not null,
    status varchar(20) not null,
    credit_terms integer not null,
    contract_start date,
    contract_end date,
    beneficiary_name varchar(150),
    bank_name varchar(150),
    iban varchar(40),
    account_number varchar(100),
    swift_code varchar(30),
    currency varchar(3) not null,
    archived boolean not null default false
);

create table vendor_contacts (
    vendor_id bigint not null references vendors(id),
    position integer not null,
    name varchar(150) not null,
    mobile varchar(40) not null,
    email varchar(150),
    primary key (vendor_id, position)
);

create table vendor_files (
    id bigint generated by default as identity primary key,
    vendor_id bigint not null references vendors(id),
    document_type varchar(40) not null,
    storage_key varchar(100) not null unique,
    original_name varchar(255) not null,
    content_type varchar(100) not null,
    size_bytes bigint not null,
    created_at timestamp with time zone not null,
    unique (vendor_id, document_type)
);

create index idx_vendors_status on vendors(status);
create index idx_vendor_files_vendor on vendor_files(vendor_id);
