create table customers (
    id bigint generated by default as identity primary key,
    type varchar(20) not null,
    name varchar(150) not null,
    name_key varchar(150) not null,
    phone varchar(40) not null,
    email varchar(150) not null,
    address varchar(500),
    status varchar(20) not null,
    created_at timestamp with time zone not null,
    registration_number varchar(100),
    tax_number varchar(30),
    billing_contact_name varchar(150),
    billing_address varchar(500),
    billing_city varchar(100),
    billing_country varchar(100),
    payment_terms varchar(100),
    waiting_rate_per_hour numeric(12,2),
    included_waiting_minutes integer,
    waiting_billing_increment_minutes integer,
    unique (type, name_key)
);

create index idx_customers_type_status on customers(type, status);

create table customer_quotes (
    id varchar(36) primary key,
    customer_id bigint not null references customers(id),
    number varchar(60) not null unique,
    version integer not null,
    status varchar(20) not null,
    issue_date date not null,
    offer_valid_until date,
    effective_from date,
    effective_to date,
    tax_percent numeric(5,2) not null,
    payment_terms varchar(100),
    notes text,
    routes_json text not null,
    monthly_json text not null,
    services_json text not null,
    extras_json text not null,
    approved_by varchar(150),
    approval_date date,
    approval_method varchar(40),
    approval_note varchar(1000),
    approval_file_name varchar(255),
    created_at timestamp with time zone not null,
    unique (customer_id, version)
);

create index idx_quotes_customer_status on customer_quotes(customer_id, status);

create table quote_evidence (
    quote_id varchar(36) primary key references customer_quotes(id),
    file_name varchar(255) not null,
    content_type varchar(100) not null,
    file_data bytea not null
);
