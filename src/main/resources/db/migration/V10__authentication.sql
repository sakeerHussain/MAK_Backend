CREATE TABLE auth_accounts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK(role IN ('Admin','Manager','Operations','Finance','Viewer')),
 status VARCHAR(20) NOT NULL CHECK(status IN ('Pending','Active','Inactive')),
 session_version BIGINT NOT NULL DEFAULT 0,failed_attempts INTEGER NOT NULL DEFAULT 0,
 locked_until TIMESTAMP WITH TIME ZONE, created_at TIMESTAMP WITH TIME ZONE NOT NULL,last_login_at TIMESTAMP WITH TIME ZONE
);
CREATE TABLE auth_password_resets(token_hash VARCHAR(64) PRIMARY KEY,account_id BIGINT NOT NULL REFERENCES auth_accounts(id),expires_at TIMESTAMP WITH TIME ZONE NOT NULL);
CREATE TABLE auth_audit(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_id BIGINT REFERENCES auth_accounts(id),target_id BIGINT REFERENCES auth_accounts(id),event VARCHAR(40) NOT NULL,summary VARCHAR(300) NOT NULL,created_at TIMESTAMP WITH TIME ZONE NOT NULL);
CREATE INDEX ix_auth_audit_time ON auth_audit(created_at);
