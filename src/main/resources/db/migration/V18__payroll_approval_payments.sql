CREATE TABLE payroll_approvals (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payroll_id BIGINT NOT NULL REFERENCES payroll_drafts(id),
 net_cash NUMERIC(18,2) NOT NULL CHECK (net_cash>=0),
 payload TEXT NOT NULL,
 review_note VARCHAR(1000) NOT NULL,
 approved_at TIMESTAMP WITH TIME ZONE NOT NULL,
 approved_by BIGINT NOT NULL REFERENCES auth_accounts(id),
 reopened_at TIMESTAMP WITH TIME ZONE,
 reopened_by BIGINT REFERENCES auth_accounts(id),
 reopen_reason VARCHAR(1000)
);
ALTER TABLE payroll_drafts ADD COLUMN approval_id BIGINT REFERENCES payroll_approvals(id);
CREATE INDEX ix_payroll_approvals_payroll ON payroll_approvals(payroll_id);

CREATE TABLE payroll_payments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payroll_id BIGINT NOT NULL REFERENCES payroll_drafts(id),
 payee_id BIGINT NOT NULL REFERENCES payroll_payees(id),
 approval_id BIGINT NOT NULL REFERENCES payroll_approvals(id),
 request_key VARCHAR(36) NOT NULL,
 request_data TEXT NOT NULL,
 request_receipt_hash VARCHAR(64),
 method VARCHAR(4) NOT NULL CHECK (method IN ('BANK','CASH')),
 amount NUMERIC(12,2) NOT NULL CHECK (amount>0),
 paid_on DATE NOT NULL,
 reference VARCHAR(150) NOT NULL,
 active_reference VARCHAR(160),
 notes VARCHAR(1000) NOT NULL,
 receiving_account TEXT,
 recorded_at TIMESTAMP WITH TIME ZONE NOT NULL,
 recorded_by BIGINT NOT NULL REFERENCES auth_accounts(id),
 reversed_at TIMESTAMP WITH TIME ZONE,
 reversed_by BIGINT REFERENCES auth_accounts(id),
 reversal_reason VARCHAR(1000),
 receipt_key VARCHAR(100),
 receipt_name VARCHAR(255),
 receipt_type VARCHAR(100),
 receipt_size BIGINT,
 UNIQUE (payroll_id, request_key),
 UNIQUE (payee_id, active_reference)
);
CREATE INDEX ix_payroll_payments_payroll ON payroll_payments(payroll_id);
