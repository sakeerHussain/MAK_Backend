ALTER TABLE vehicles ADD COLUMN maintenance_return_status VARCHAR(30);
CREATE TABLE maintenance_jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 job_id VARCHAR(50) UNIQUE,
 vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
 work_type VARCHAR(40) NOT NULL,
 work_item VARCHAR(80) NOT NULL,
 status VARCHAR(20) NOT NULL,
 service_date DATE NOT NULL,
 odometer_km BIGINT,
 garage VARCHAR(200),
 next_service_date DATE,
 next_service_odometer_km BIGINT,
 notes TEXT,
 completed_tasks TEXT NOT NULL,
 total_amount NUMERIC(14,2) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT ck_maintenance_status CHECK(status IN ('Open','In Progress','Completed','Cancelled'))
);
CREATE INDEX ix_maintenance_vehicle_status ON maintenance_jobs(vehicle_id,status);
CREATE TABLE maintenance_expenses (
 job_id BIGINT NOT NULL REFERENCES maintenance_jobs(id),
 line_order INTEGER NOT NULL,
 client_key VARCHAR(80) NOT NULL,
 category VARCHAR(30) NOT NULL,
 amount NUMERIC(12,2) NOT NULL,
 description VARCHAR(1000) NOT NULL,
 receipt_key VARCHAR(100),
 receipt_name VARCHAR(255),
 receipt_type VARCHAR(100),
 receipt_size BIGINT,
 PRIMARY KEY(job_id,line_order),
 CONSTRAINT ck_expense_amount CHECK(amount>0)
);
