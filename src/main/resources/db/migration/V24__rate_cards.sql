-- Standard rate cards: one revision series, each revision immutable once published.
CREATE TABLE rate_cards (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 revision INT NOT NULL UNIQUE,
 status VARCHAR(12) NOT NULL CHECK (status IN ('DRAFT','PUBLISHED')),
 effective_from DATE NOT NULL,
 effective_to DATE,
 tax_percent NUMERIC(5,2) NOT NULL,
 grace_minutes INT NOT NULL,
 extra_km_rate NUMERIC(12,2),
 overtime_hour_rate NUMERIC(12,2),
 extra_driver_rate NUMERIC(12,2),
 notes VARCHAR(1000),
 revised_from_id BIGINT REFERENCES rate_cards(id),
 digest VARCHAR(64),
 created_by BIGINT NOT NULL REFERENCES auth_accounts(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 published_by BIGINT REFERENCES auth_accounts(id),
 published_at TIMESTAMP WITH TIME ZONE,
 version BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX ix_rate_cards_status_from ON rate_cards(status, effective_from);

-- A line prices a vehicle class, or one vehicle (override), for one billing unit.
CREATE TABLE rate_card_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rate_card_id BIGINT NOT NULL REFERENCES rate_cards(id) ON DELETE CASCADE,
 vehicle_class VARCHAR(20) NOT NULL,
 vehicle_id BIGINT REFERENCES vehicles(id),
 unit VARCHAR(10) NOT NULL CHECK (unit IN ('HOUR','DAY','WEEK','MONTH')),
 amount NUMERIC(12,2) NOT NULL CHECK (amount > 0)
);
CREATE INDEX ix_rate_card_lines_card ON rate_card_lines(rate_card_id);

CREATE TABLE rate_card_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rate_card_id BIGINT NOT NULL REFERENCES rate_cards(id) ON DELETE CASCADE,
 actor_id BIGINT NOT NULL REFERENCES auth_accounts(id),
 action VARCHAR(20) NOT NULL,
 reason VARCHAR(500),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_rate_card_events_card ON rate_card_events(rate_card_id, id);
