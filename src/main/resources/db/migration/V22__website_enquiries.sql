CREATE TABLE website_enquiries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 submission_id VARCHAR(36) NOT NULL UNIQUE, fingerprint VARCHAR(64) NOT NULL,
 kind VARCHAR(10) NOT NULL, name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL,
 phone VARCHAR(40), company VARCHAR(150), subject VARCHAR(120) NOT NULL,
 message VARCHAR(4000) NOT NULL, category VARCHAR(80), preference VARCHAR(80),
 location VARCHAR(300), pickup_date DATE, return_date DATE, vehicle_id BIGINT,
 vehicle_name VARCHAR(200), status VARCHAR(20) NOT NULL,
 internal_note VARCHAR(4000) NOT NULL DEFAULT '', version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_by BIGINT REFERENCES auth_accounts(id)
);
CREATE INDEX ix_website_enquiries_status_created ON website_enquiries(status, created_at DESC);
CREATE TABLE website_enquiry_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 enquiry_id BIGINT NOT NULL REFERENCES website_enquiries(id),
 actor_id BIGINT NOT NULL REFERENCES auth_accounts(id),
 previous_status VARCHAR(20) NOT NULL, new_status VARCHAR(20) NOT NULL,
 note_changed BOOLEAN NOT NULL, created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
