-- Payroll has its own payee identity so an Employee and Driver with the same
-- staff number cannot receive duplicate payroll for the same calendar month.
CREATE TABLE payroll_payees (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 staff_type VARCHAR(10) NOT NULL CHECK (staff_type IN ('EMPLOYEE','DRIVER')),
 staff_id BIGINT NOT NULL,
 staff_key VARCHAR(50) NOT NULL UNIQUE,
 UNIQUE (staff_type, staff_id)
);
CREATE TABLE payroll_profiles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payee_id BIGINT NOT NULL REFERENCES payroll_payees(id),
 effective_month VARCHAR(7) NOT NULL,
 payload TEXT NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_by BIGINT NOT NULL REFERENCES auth_accounts(id),
 UNIQUE (payee_id, effective_month)
);
CREATE TABLE payroll_drafts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 payee_id BIGINT NOT NULL REFERENCES payroll_payees(id),
 period VARCHAR(7) NOT NULL,
 profile_id BIGINT NOT NULL REFERENCES payroll_profiles(id),
 profile_version BIGINT NOT NULL,
 staff_name VARCHAR(150) NOT NULL,
 staff_number VARCHAR(50) NOT NULL,
 snapshot TEXT NOT NULL,
 adjustments TEXT NOT NULL,
 notes VARCHAR(2000) NOT NULL,
 version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_by BIGINT NOT NULL REFERENCES auth_accounts(id),
 UNIQUE (payee_id, period)
);
CREATE INDEX ix_payroll_drafts_period ON payroll_drafts(period);
