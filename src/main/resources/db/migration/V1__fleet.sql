create table vehicles (
    id bigint generated by default as identity primary key,
    registration varchar(50) not null unique,
    vehicle_id varchar(50) not null unique,
    make varchar(100) not null,
    model varchar(100) not null,
    registration_year integer not null,
    color varchar(60),
    door_no varchar(60),
    chassis_no varchar(100),
    type varchar(30) not null,
    seats integer not null,
    transmission varchar(30) not null,
    fuel_type varchar(30) not null,
    hourly_rate numeric(12,2),
    daily_rate numeric(12,2) not null,
    monthly_rate numeric(12,2),
    rate_currency varchar(3) not null,
    ownership varchar(20) not null,
    vendor varchar(150),
    status varchar(30) not null,
    custodian varchar(150),
    on_site boolean not null,
    listed_for_booking boolean not null,
    show_on_public_site boolean not null,
    service_interval_km bigint,
    last_service_km bigint,
    current_odometer_km bigint,
    oil_interval_km bigint,
    last_oil_km bigint,
    tyre_interval_km bigint,
    last_tyre_km bigint,
    brake_interval_km bigint,
    last_brake_km bigint
);

create table vehicle_tags (
    vehicle_id bigint not null references vehicles(id),
    tag_order integer not null,
    tag varchar(80) not null,
    primary key (vehicle_id, tag_order)
);

create table vehicle_files (
    id bigint generated by default as identity primary key,
    vehicle_id bigint not null references vehicles(id),
    kind varchar(16) not null,
    document_type varchar(32),
    expiry_date date,
    storage_key varchar(100) not null unique,
    original_name varchar(255) not null,
    content_type varchar(100) not null,
    size_bytes bigint not null,
    created_at timestamp with time zone not null
);

create index idx_vehicle_files_vehicle on vehicle_files(vehicle_id);
create index idx_vehicles_status on vehicles(status);
