create table rental_records (
    id bigint generated by default as identity primary key,
    kind varchar(20) not null,
    reference varchar(50) unique,
    booking_type varchar(20) not null,
    status varchar(20) not null,
    customer_id bigint references customers(id),
    vehicle_id bigint references vehicles(id),
    driver_id bigint references drivers(id),
    pickup_at timestamp not null,
    return_at timestamp not null,
    total_amount numeric(14,2) not null,
    received_amount numeric(14,2) not null default 0,
    refunded_amount numeric(14,2) not null default 0,
    payload text not null,
    created_at timestamp with time zone not null,
    constraint rental_kind_check check (kind in ('Individual', 'Corporate')),
    constraint rental_period_check check (return_at > pickup_at)
);
create index idx_rental_kind_status on rental_records(kind, status);
create index idx_rental_vehicle_period on rental_records(vehicle_id, pickup_at, return_at);
create index idx_rental_driver_period on rental_records(driver_id, pickup_at, return_at);
create index idx_rental_customer on rental_records(customer_id);

create table rental_payments (
    id bigint generated by default as identity primary key,
    rental_id bigint not null references rental_records(id),
    kind varchar(10) not null,
    amount numeric(14,2) not null,
    created_at timestamp with time zone not null,
    constraint rental_payment_kind_check check (kind in ('Payment', 'Refund')),
    constraint rental_payment_amount_check check (amount > 0)
);
create index idx_rental_payments_rental on rental_payments(rental_id);

create table invoices (
    id bigint generated by default as identity primary key,
    number varchar(50) unique,
    kind varchar(20) not null,
    status varchar(20) not null,
    total_amount numeric(14,2) not null,
    paid_amount numeric(14,2) not null,
    payload text not null,
    created_at timestamp with time zone not null,
    issued_at timestamp with time zone
);
create table invoice_sources (
    invoice_id bigint not null references invoices(id),
    rental_id bigint not null unique references rental_records(id),
    primary key(invoice_id, rental_id)
);
create table invoice_payments (
    id bigint generated by default as identity primary key,
    invoice_id bigint not null references invoices(id),
    kind varchar(10) not null,
    amount numeric(14,2) not null,
    paid_on date not null,
    method varchar(80),
    reference varchar(120),
    constraint invoice_payment_kind_check check (kind in ('Payment', 'Refund')),
    constraint invoice_payment_amount_check check (amount > 0)
);
