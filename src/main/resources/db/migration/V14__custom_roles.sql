CREATE TABLE auth_roles (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(80) NOT NULL UNIQUE, description VARCHAR(300) NOT NULL,
 permissions_json TEXT NOT NULL, version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL, updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);
ALTER TABLE auth_accounts ADD COLUMN custom_role_id BIGINT REFERENCES auth_roles(id);
CREATE INDEX ix_accounts_custom_role ON auth_accounts(custom_role_id);
CREATE TABLE auth_invitations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(200) NOT NULL,email VARCHAR(254) NOT NULL,
 role VARCHAR(20) NOT NULL,custom_role_id BIGINT REFERENCES auth_roles(id),
 token_hash VARCHAR(64) NOT NULL UNIQUE,status VARCHAR(20) NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
 created_by BIGINT NOT NULL REFERENCES auth_accounts(id)
);
