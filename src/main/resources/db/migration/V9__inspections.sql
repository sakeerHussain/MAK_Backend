CREATE TABLE inspections (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 inspection_id VARCHAR(50) UNIQUE,
 vehicle_id BIGINT NOT NULL REFERENCES vehicles(id),
 type VARCHAR(30) NOT NULL,
 vehicle_condition VARCHAR(20) NOT NULL,
 inspection_date DATE NOT NULL,
 inspector VARCHAR(200) NOT NULL,
 odometer_km BIGINT NOT NULL CHECK(odometer_km>=0),
 fuel_level INTEGER NOT NULL CHECK(fuel_level IN (0,25,50,75,100)),
 booking_id BIGINT REFERENCES rental_records(id),
 notes TEXT,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT ck_inspection_type CHECK(type IN ('Pre-trip','Post-trip','Routine','Damage assessment')),
 CONSTRAINT ck_inspection_condition CHECK(vehicle_condition IN ('Excellent','Good','Fair','Poor','Damaged'))
);
CREATE INDEX ix_inspections_vehicle_date ON inspections(vehicle_id,inspection_date);
CREATE INDEX ix_inspections_booking ON inspections(booking_id);
CREATE TABLE inspection_photos (
 inspection_id BIGINT NOT NULL REFERENCES inspections(id),
 photo_order INTEGER NOT NULL,
 storage_key VARCHAR(100) NOT NULL,
 name VARCHAR(255) NOT NULL,
 content_type VARCHAR(100) NOT NULL,
 file_size BIGINT NOT NULL,
 PRIMARY KEY(inspection_id,photo_order)
);
