CREATE TABLE email_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_kind VARCHAR(20) NOT NULL,
    record_id BIGINT NOT NULL,
    recipient VARCHAR(254) NOT NULL,
    subject VARCHAR(200) NOT NULL,
    body TEXT NOT NULL,
    attachment TEXT,
    attachment_name VARCHAR(100),
    status VARCHAR(20) NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    next_attempt_at TIMESTAMP WITH TIME ZONE NOT NULL,
    sent_at TIMESTAMP WITH TIME ZONE,
    last_error VARCHAR(300),
    CONSTRAINT ck_email_status CHECK (status IN ('Queued','Failed','Sent'))
);
CREATE INDEX ix_email_due ON email_outbox(status,next_attempt_at);
CREATE INDEX ix_email_record ON email_outbox(record_kind,record_id,id);
