CREATE TABLE booking_alerts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 rental_id BIGINT NOT NULL REFERENCES rental_records(id),
 kind VARCHAR(20) NOT NULL,
 alert_key VARCHAR(250) NOT NULL UNIQUE,
 type VARCHAR(40) NOT NULL,
 priority VARCHAR(20) NOT NULL,
 title VARCHAR(200) NOT NULL,
 snapshot TEXT NOT NULL,
 actionable BOOLEAN NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE NOT NULL,
 resolved_at TIMESTAMP WITH TIME ZONE,
 escalated BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE TABLE booking_alert_recipients(
 alert_id BIGINT NOT NULL REFERENCES booking_alerts(id),
 account_id BIGINT NOT NULL REFERENCES auth_accounts(id),
 read_at TIMESTAMP WITH TIME ZONE,
 acknowledged_at TIMESTAMP WITH TIME ZONE,
 email_queued BOOLEAN NOT NULL DEFAULT FALSE,
 PRIMARY KEY(alert_id,account_id)
);
CREATE TABLE booking_notification_events(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 account_id BIGINT NOT NULL REFERENCES auth_accounts(id),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_booking_alert_open ON booking_alerts(resolved_at,priority);
CREATE INDEX ix_booking_recipient_account ON booking_alert_recipients(account_id,alert_id);
CREATE INDEX ix_booking_event_account ON booking_notification_events(account_id,id);
