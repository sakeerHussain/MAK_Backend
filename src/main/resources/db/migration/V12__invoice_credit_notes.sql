alter table invoices add column credited_amount numeric(14,2) not null default 0;
alter table invoices add constraint invoice_credit_limit check (credited_amount >= 0 and credited_amount <= total_amount);
create table invoice_credit_notes (
    id bigint generated by default as identity primary key,
    invoice_id bigint not null references invoices(id),
    request_key varchar(36) not null,
    request_fingerprint varchar(64) not null,
    total_amount numeric(14,2) not null check (total_amount > 0),
    issued_at timestamp with time zone not null,
    payload text not null,
    constraint credit_note_request_unique unique (invoice_id,request_key)
);
create index credit_note_invoice on invoice_credit_notes(invoice_id);
