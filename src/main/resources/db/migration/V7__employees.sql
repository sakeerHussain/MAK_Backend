create table employees (
    id bigint generated by default as identity primary key,
    employee_id varchar(50) not null unique,
    name varchar(150) not null,
    phone varchar(40) not null,
    phone_key varchar(40) not null unique,
    email varchar(150),
    category varchar(40) not null,
    nationality varchar(100),
    job_title varchar(100) not null,
    department varchar(50) not null,
    manager varchar(150),
    id_number varchar(100),
    iqama_expiry date,
    years_experience integer,
    employment_type varchar(30) not null,
    vendor varchar(150),
    status varchar(20) not null,
    company_id varchar(100),
    joined_on date,
    official_number varchar(40),
    hourly_rate numeric(12,2),
    daily_rate numeric(12,2),
    monthly_salary numeric(12,2) not null,
    passport_number varchar(100),
    passport_expiry date,
    contract_id varchar(100),
    contract_expiry date,
    licence_number varchar(100),
    licence_expiry date,
    blood_group varchar(5),
    insurance_number varchar(100),
    insurance_expiry date,
    emergency_ksa varchar(40),
    emergency_home varchar(40),
    home_address varchar(500),
    payroll_count integer not null default 0,
    archived boolean not null default false
);

create table employee_files (
    id bigint generated by default as identity primary key,
    employee_id bigint not null references employees(id),
    kind varchar(20) not null,
    document_type varchar(40),
    expiry_date date,
    storage_key varchar(100) unique,
    original_name varchar(255),
    content_type varchar(100),
    size_bytes bigint,
    created_at timestamp with time zone not null
);

create index idx_employees_status on employees(status);
create index idx_employee_files_employee on employee_files(employee_id);
